func optimizationBoundaryInput(n, kind int) []byte {
	raw := make([]byte, n)
	x := uint64(0x9e3779b97f4a7c15)
	for i := range raw {
		x ^= x << 13
		x ^= x >> 7
		x ^= x << 17
		raw[i] = byte(x)
	}
	if kind == 1 {
		for i := 71; i+8 < n; i += 127 {
			copy(raw[i:i+8], raw[i-63:i-55])
		}
	}
	if kind == 2 {
		for i := 73; i < n; i++ {
			raw[i] = raw[i%73]
		}
		for _, off := range []int{16, 127, 128, 129, 143, 144, 145, 255, 256, 257, 271, 272, 273, 399, 400, 401} {
			if off+73 < n {
				raw[off+73] ^= 0x55
			}
		}
	}
	return raw
}

