// A miss has already advanced X6 to the next canonical probe. A stride
// boundary changes X7 only; rebuild X6 and the mask on entry after a match
// or a search-window transition, where the emitter can clobber them.
func sparseRefreshStride(s string) string {
	for _, v := range []struct{ name, win, cache, stop, scale, mask string }{
		{"encodeBlockPrefix8M", "24", "40", "window_limit_", "", "prefixVectorMask"},
		{"encodeBlockPrefix2M", "8", "24", "emit_remainder_", "\tVPSLLD $8, @reg@, @reg@\n", "compactTupleMask"},
	} {
		recalc := "stride_recalc_" + v.name
		init := "stride_init_" + v.name
		a := strings.Index(s, recalc+":")
		must(a >= 0, "refresh stride")
		last := "\tJMP stride_body_" + v.name + "\n"
		b := strings.Index(s[a:], last)
		must(b > 0, "refresh end")
		b += a + len(last)
		r := strings.NewReplacer("@name@", v.name, "@window@", v.win, "@cache@", v.cache,
			"@stop@", v.stop+v.name, "@mask@", v.mask,
			"@scale6@", strings.ReplaceAll(v.scale, "@reg@", "X6"),
			"@scale7@", strings.ReplaceAll(v.scale, "@reg@", "X7"))
		s = s[:a] + r.Replace(refreshStrideBody) + s[b:]
		s = replace(s, "JMP "+recalc+"\n", "JMP "+init+"\n")
	}
	return s
}

const refreshStrideBody = `stride_init_@name@:
	VMOVD DI, X6
	VPSHUFD $0, X6, X6
	VPADDD prefixVectorDelta<>+0(SB), X6, X6
@scale6@	VMOVDQU @mask@<>+0(SB), X8
stride_recalc_@name@:
	MOVL DI, R15
	SUBL CX, R15
	MOVL R15, R10
	ORL $63, R10
	LEAL 1(CX)(R10*1), R10
	SHRL $6, R15
	ADDL $4, R15
	LEAL (DI)(R15*1), DX
	CMPQ DX, @window@(SP)
	JAE @stop@
	MOVQ @window@(SP), R11
	SUBQ R15, R11
	CMPQ R10, R11
	CMOVQGT R11, R10
	MOVQ R10, @cache@(SP)
	VMOVD R15, X7
	VPSHUFD $0, X7, X7
@scale7@	JMP stride_body_@name@
`
