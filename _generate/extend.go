// The hash multiplier has sixteen zero low bits, so the extra high bytes in
// each overlapping 8-byte load do not affect the 15-bit bucket. All three
// loads are within the unchanged 17-byte source margin. Using memory operands
// lets the processor issue the three source loads independently.
func sparseMemoryHash(s string) string {
	const old = `	MOVQ (R8)(DI*1), R10
	MOVQ R10, R11
	IMULQ R9, R11
	SHRQ $49, R11
	MOVQ R10, R12
	SHRQ $8, R12
	IMULQ R9, R12
	SHRQ $49, R12
	MOVQ R10, R13
	SHRQ $16, R13
	IMULQ R9, R13
	SHRQ $49, R13
`
	const new = `	MOVQ R9, R11
	IMULQ (R8)(DI*1), R11
	SHRQ $49, R11
	MOVQ R9, R12
	IMULQ 1(R8)(DI*1), R12
	SHRQ $49, R12
	MOVQ R9, R13
	IMULQ 2(R8)(DI*1), R13
	SHRQ $49, R13
	MOVQ (R8)(DI*1), R10
`
	must(strings.Count(s, old) == 2, "two memory hash loops")
	return strings.ReplaceAll(s, old, new)
}

