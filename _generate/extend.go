// On a miss, the first two candidate positions are not needed. Compare their
// stored words directly, and keep the third read after both canonical stores.
// The original vector selection is used for first/second hits and repeats;
// it reuses the three hashes and the shuffled source computed on entry.
func sparseScalarMiss(s string) string {
	for _, v := range []struct{ name, loop, old0, old1, old2, put01, put2, idx, cand, cmp string }{
		{"encodeBlockPrefix8M", "search_valid_", "X2", "X3", "X4", "X1", "X5", "R12", "R9", "X1"},
		{"encodeBlockPrefix2M", "search_fast_", "X1", "X2", "X3", "X3", "X4", "R11", "DX", "X5"},
	} {
		name := v.name
		a := strings.Index(s, "stride_body_"+name+":")
		must(a >= 0, "scalar probe body")
		b := strings.Index(s[a:], "\nstride_recalc_"+name+":") + a
		must(b > a, "scalar probe end")
		p := strings.NewReplacer("@name@", name, "@loop@", v.loop+name,
			"@old0@", v.old0, "@old1@", v.old1, "@old2@", v.old2, "@put01@", v.put01,
			"@put2@", v.put2, "@idx@", v.idx, "@cand@", v.cand, "@cmp@", v.cmp)
		s = s[:a] + p.Replace(sparseScalarBody) + s[b:]
	}
	return s
}

