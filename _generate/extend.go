// Cache only after the first miss. Immediate hits retain the original scalar
// entry; cached misses fall through while repeats rejoin the original handler.
func lazyScalarMedium(s string) string {
	name := "encodeBlockAsm512K"
	a := strings.Index(s, "// func "+name+"(")
	must(a >= 0, "lazy function")
	b := strings.Index(s[a+8:], "// func ")
	must(b >= 0, "lazy function end")
	b += a + 8
	body := s[a:b]
	start := strings.Index(body, "search_loop_"+name+":")
	must(start >= 0, "lazy loop")
	match := regexp.MustCompile(`\tJNE\s+no_repeat_found_` + name + `\n`).FindStringIndex(body[start:])
	must(match != nil, "lazy repeat branch")
	end := start + match[1]
	prefix := body[start:end]
	a0 := strings.Index(body, "no_repeat_found_"+name+":")
	b0 := strings.Index(body, "\ncandidate3_match_"+name+":")
	must(b0 > a0, "lazy miss")
	miss := body[a0:b0]
	fast := strings.ReplaceAll(prefix, "search_loop_"+name+":", "search_fast_lazy_"+name+":")
	fast = strings.ReplaceAll(fast, "no_repeat_found_"+name, "no_repeat_lazy_"+name)
	fast = rx(fast, `SUBQ\s+16\(SP\), AX`, `SUBQ BP, AX`, 1)
	fast = rx(fast, `\tMOVQ\s+\$0xcf1bbcdcbf9b0000, R10\n`, "", 1)
	fast = rx(fast, `IMULQ\s+R10,`, `IMULQ R15,`, 3)
	fast = rx(fast, `\tMOVL\s+BX, R10\n\tSUBQ\s+24\(SP\), R10\n`, "", 1)
	fast = rx(fast, `1\(SI\)\(R10\*1\)`, `1(R14)(BX*1)`, 1)
	fast = rx(fast, `\tJNE\s+no_repeat_lazy_`+name+`\n`, "\tJE repeat_inline_lazy_"+name+"\n", 1)
	cachedMiss := strings.ReplaceAll(miss, "no_repeat_found_"+name, "no_repeat_lazy_"+name)
	cachedMiss = rx(cachedMiss, `(\tJMP\s+)search_loop_`+name+`\n`, `${1}search_fast_lazy_`+name+"\n", 1)
	originalMiss := rx(miss, `(\tJMP\s+)search_loop_`+name+`\n`, `${1}search_cache_lazy_`+name+"\n", 1)
	body = body[:a0] + originalMiss + body[b0:]
	body = body[:end] + "repeat_inline_lazy_" + name + ":\n" + body[end:]
	body += "\n// Cache only after an actual miss; immediate matches/repeats retain the original entry.\nsearch_cache_lazy_" + name + ":\n\tMOVQ 16(SP), BP\n\tMOVQ SI, R14\n\tSUBQ 24(SP), R14\n\tMOVQ $0xcf1bbcdcbf9b0000, R15\n" + fast + cachedMiss + "\n"
	return s[:a] + body + s[b:]
}

// Only the <=2MiB prefix kernel uses this hint. The actual third read remains
// after the original two writes, so alias forwarding stays architectural.
func prefetch2M(s string) string {
	name := "encodeBlockPrefix2M"
	a := strings.Index(s, "search_loop_"+name+":")
	must(a >= 0, "prefetch loop")
	b := strings.Index(s[a:], "\nprefix_hit_"+name+":") + a
	must(b > a, "prefetch hit")
	body := s[a:b]
	re := regexp.MustCompile(`(\tMOVQ\s+R10, R11\n\tIMULQ\s+R9, R11\n\tSHRQ\s+\$0x31, R11\n)(\tMOVQ\s+R10, R12\n\tSHRQ\s+\$0x08, R12\n\tIMULQ\s+R9, R12\n\tSHRQ\s+\$0x31, R12\n)(\tVMOVQ\s+\(BX\)\(R11\*8\), X\d\n)`)
	must(len(re.FindAllStringIndex(body, -1)) == 1, "first load schedule")
	body = re.ReplaceAllString(body, `${1}${3}${2}`)
	body = rx(body, `\tMOVQ\s+R10, R11\n\tSHRQ\s+\$0x10, R11\n\tIMULQ\s+R9, R11\n\tSHRQ\s+\$0x31, R11\n`, "\tMOVQ R13, R11\n", 1)
	early := "\tMOVQ R10, R13\n\tSHRQ $16, R13\n\tIMULQ R9, R13\n\tSHRQ $49, R13\n\tPREFETCHT0 (BX)(R13*8)\n"
	re = regexp.MustCompile(`(\tVMOVQ\s+\(BX\)\(R12\*8\), X2\n)`)
	must(len(re.FindAllStringIndex(body, -1)) == 1, "second load schedule")
	body = re.ReplaceAllStringFunc(body, func(block string) string { return block + early })
	return s[:a] + body + s[b:]
}

