// Keep the scalar step and the vector of three current positions until the
// skip term changes. Every probe is still at s+4+((s-nextEmit)>>6), with
// the canonical test against the current search window before any load.
// Checked windows, match selection, and dictionary layout are unchanged.
func sparseCachedStride(s string) string {
	for _, v := range []struct{ name, loop, end, window, cache, oldFrame, newFrame, stop string }{
		{"encodeBlockPrefix8M", "search_valid_", "search_checked_", "24", "40", "$40-64", "$48-64", "window_limit_"},
		{"encodeBlockPrefix2M", "search_fast_", "prefix_hit_", "8", "24", "$24-64", "$32-64", "emit_remainder_"},
	} {
		name := v.name
		start := v.loop + name
		recalc := "stride_recalc_" + name
		body := "stride_body_" + name
		s = replace(s, "TEXT ·"+name+"(SB), "+v.oldFrame, "TEXT ·"+name+"(SB), "+v.newFrame)
		a := strings.Index(s, start+":")
		b := strings.Index(s[a:], "\n"+v.end+name+":") + a
		must(a >= 0 && b > a, "stride loop bounds")
		loop := s[a:b]
		// X6 is the current {s,s+1,s+2,s+3}; X7 is the cached stride.
		// X8 holds the immutable byte shuffle mask across the miss loop.
		loop = rx(loop, `\tVMOVD\s+DI, X6\n\tVPSHUFD\s+\$0x00, X6, X6\n\tVPADDD\s+prefixVectorDelta<>\+0\(SB\), X6, X6\n`, "", 1)
		loop = rx(loop, `VPSHUFB\s+prefixVectorMask<>\+0\(SB\), X0, X0`, `VPSHUFB X8, X0, X0`, 1)
		loop = rx(loop, `\tMOVQ\s+DX, DI\n`, "\tVPADDD X7, X6, X6\n\tMOVQ DX, DI\n", 1)
		cut := strings.Index(loop, "(R8)(DI*1), R10")
		must(cut >= 0, "stride source load")
		cut = strings.LastIndex(loop[:cut], "\n") + 1
		tail := ""
		if v.window == "24" {
			// Keep the old checked-loop alignment and only redirect valid entries.
			const alignment = " PCALIGN $32"
			must(strings.HasSuffix(loop, alignment), "stride checked alignment")
			loop = strings.TrimSuffix(loop, alignment)
			tail = "\n" + alignment
		}
		// Branch to the original end/window handler with the real nextS in DX.
		fix := strings.NewReplacer("@start@", start, "@body@", body, "@recalc@", recalc,
			"@window@", v.window, "@cache@", v.cache, "@stop@", v.stop+name)
		s = s[:a] + fix.Replace(strideEnter) + loop[cut:] + fix.Replace(strideRecalc) + tail + s[b:]
		if v.window == "24" {
			s = replace(s, " JMP "+start+"\n", " JMP "+recalc+"\n")
		} else {
			// The unbounded entry sets R9 and falls through before the loop.
			s = replace(s, "search_loop_"+name+":\n\tMOVQ $0xcf1bbcdcbf9b0000, R9\n\n", "search_loop_"+name+":\n\tMOVQ $0xcf1bbcdcbf9b0000, R9\n\tJMP "+recalc+"\n\n")
		}
	}
	return s
}

