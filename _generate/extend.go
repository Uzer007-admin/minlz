// Extend the complete-block wrapper, preserving each canonical short parser.
func wholeThrough16K(s string) string {
	s = wholeExtended(s)
	if e := os.WriteFile("../encode_medium_whole_dispatch_amd64.s", []byte(mediumWholeDispatcher), 0644); e != nil {
		panic(e)
	}
	for _, item := range []struct{ file, old, name, out string }{
		{"encode_short4k_amd64.s", "encodeBlockShort4KAVX2", "encodeSmallWhole4KAVX2Asm", "encode_whole4k_avx2_amd64.s"},
		{"encode_short4k_sse_amd64.s", "encodeBlockShort4KSSE2", "encodeSmallWhole4KSSE2Asm", "encode_whole4k_sse_amd64.s"},
		{"encode_short16k_amd64.s", "encodeBlockShort16K", "encodeSmallWhole16KAsm", "encode_whole16k_amd64.s"},
	} {
		data, e := os.ReadFile("../" + item.file)
		if e != nil {
			panic(e)
		}
		raw := string(data)
		a := strings.Index(raw, "// func "+item.old+"(")
		must(a >= 0, "whole medium function "+item.old)
		b := strings.Index(raw[a+8:], "// func ")
		if b < 0 {
			b = len(raw)
		} else {
			b += a + 8
		}
		body := strings.ReplaceAll(raw[a:b], item.old, item.name)
		re := regexp.MustCompile(`\tMOVQ\s+dst_base\+0\(FP\), SI\n`)
		must(len(re.FindAllStringIndex(body, -1)) == 1, "whole medium header "+item.name)
		body = re.ReplaceAllStringFunc(body, func(old string) string { return old + wholeMediumHeader })
		body = regexp.MustCompile(`\bwhole_(\w+)\b`).ReplaceAllString(body, `whole_`+item.name+`_${1}`)
		header := wholeGeneratedHeader + "\n//go:build !appengine && !noasm && gc && !purego\n\n#include \"textflag.h\"\n\n"
		if e = os.WriteFile("../"+item.out, []byte(header+body), 0644); e != nil {
			panic(e)
		}
	}
	return s
}

