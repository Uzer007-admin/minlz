// Preserve the original dispatcher and its reachable symbols. The scalar
// large-block entry points use the same cached loop as the cold layout.
func copyCachedCold(cold string) {
	data, e := os.ReadFile("../asm_amd64.s")
	if e != nil {
		panic(e)
	}
	s := string(data)
	for _, pair := range [][2]string{{"8M", "encodeBlockAsm"}, {"2M", "encodeBlockAsm2MB"}} {
		suffix, normal := pair[0], pair[1]
		name := "encodeBlockCold" + suffix
		a := strings.Index(cold, "// func "+name+"(")
		must(a >= 0, "cold copy start")
		b := strings.Index(cold[a+8:], "// func ")
		if b < 0 {
			b = len(cold)
		} else {
			b += a + 8
		}
		body := strings.ReplaceAll(cold[a:b], name, normal)
		labels := regexp.MustCompile(`(?m)^(\w+):`).FindAllStringSubmatch(body, -1)
		for _, m := range labels {
			body = regexp.MustCompile(`\b`+regexp.QuoteMeta(m[1])+`\b`).ReplaceAllString(body, m[1]+"_cached_"+suffix)
		}
		a = strings.Index(s, "// func "+normal+"(")
		must(a >= 0, "normal copy start")
		b = strings.Index(s[a+8:], "// func ")
		if b < 0 {
			b = len(s)
		} else {
			b += a + 8
		}
		s = s[:a] + body + s[b:]
	}
	s = lazyScalarMedium(s)
	if e = os.WriteFile("../asm_amd64.s", []byte(s), 0644); e != nil {
		panic(e)
	}
}

// Start the first two original loads while constructing the comparison tags.
// Only independent reads move; dictionary writes retain canonical order.
func earlyTable(s string) string {
	for _, suffix := range []string{"8M", "2M"} {
		name := "encodeBlockPrefix" + suffix
		a := strings.Index(s, "search_loop_"+name+":")
		must(a >= 0, "early loop")
		b := strings.Index(s[a:], "\nprefix_hit_"+name+":") + a
		must(b > a, "early hit")
		body := s[a:b]
		re := regexp.MustCompile(`(?s)(\tMOVQ\s+\(R8\)\(DI\*1\), R10\n)(.*?)(\tMOVQ\s+R10, R11\n\tIMULQ\s+R9, R11\n\tSHRQ\s+\$0x31, R11\n\tMOVQ\s+R10, R12\n\tSHRQ\s+\$0x08, R12\n\tIMULQ\s+R9, R12\n\tSHRQ\s+\$0x31, R12\n\tVMOVQ\s+\(BX\)\(R11\*8\), X\d\n\tVMOVQ\s+\(BX\)\(R12\*8\), X\d\n)`)
		expected := 1
		pos := "X1"
		if suffix == "8M" {
			expected = 2
			pos = "X2"
		}
		must(len(re.FindAllStringIndex(body, -1)) == expected, "early load sites")
		body = re.ReplaceAllStringFunc(body, func(block string) string {
			m := re.FindStringSubmatch(block)
			pack := regexp.MustCompile(`\b`+pos+`\b`).ReplaceAllString(m[2], "X6")
			return m[1] + m[3] + pack
		})
		s = s[:a] + body + s[b:]
	}
	return s
}

// Inline the unchanged short parser, header and exact-span stored fallback in
// one ABI0 frame. Encode calls this only for reserved Fastest inputs 22..256.
func wholeSmall(s string) string {
	s = strings.ReplaceAll(s, "encodeBlockShort", "encodeSmallWholeAsm")
	s = strings.Replace(s, strings.SplitN(s, "\n", 2)[0], "// Code generated by go run postopt.go augment.go -mode whole. DO NOT EDIT.", 1)
	s = replace(s, "\tMOVQ    dst_base+0(FP), SI\n", "\tMOVQ    dst_base+0(FP), SI\n"+wholeHeader)
	s = rx(s, `\tMOVQ\s+\$0x00000000, ret\+48\(FP\)\n\tRET`, `\tJMP whole_stored`, 6)
	// rx replacement is literal except for regexp capture substitutions.
	s = strings.ReplaceAll(s, `\tJMP whole_stored`, "\tJMP whole_stored")
	return s + wholeStored
}

const wholeHeader = `	MOVQ src_len+32(FP), DX
	MOVB $0, (SI)
	CMPQ DX, $128
	JAE whole_header_two
	MOVB DL, 1(SI)
	ADDQ $2, SI
	JMP whole_header_done
whole_header_two:
	MOVQ DX, R8
	ORB $128, DL
	MOVB DL, 1(SI)
	SHRQ $7, R8
	MOVB R8, 2(SI)
	ADDQ $3, SI
whole_header_done:
`
const wholeStored = `
whole_stored:
	MOVQ dst_base+0(FP), SI
	MOVW $0, (SI)
	ADDQ $2, SI
	MOVQ src_base+24(FP), R8
	MOVQ src_len+32(FP), CX
	CMPQ CX, $32
	JB whole_stored_short
	LEAQ (R8)(CX*1), DX
	LEAQ (SI)(CX*1), R9
whole_stored_loop:
	CMPQ CX, $64
	JBE whole_stored_tail
	MOVOU (R8), X0
	MOVOU 16(R8), X1
	MOVOU 32(R8), X2
	MOVOU 48(R8), X3
	MOVOU X0, (SI)
	MOVOU X1, 16(SI)
	MOVOU X2, 32(SI)
	MOVOU X3, 48(SI)
	ADDQ $64, R8
	ADDQ $64, SI
	SUBQ $64, CX
	JMP whole_stored_loop
whole_stored_tail:
	CMPQ CX, $32
	JBE whole_stored_last
	MOVOU (R8), X0
	MOVOU 16(R8), X1
	MOVOU X0, (SI)
	MOVOU X1, 16(SI)
whole_stored_last:
	MOVOU -32(DX), X0
	MOVOU -16(DX), X1
	MOVOU X0, -32(R9)
	MOVOU X1, -16(R9)
	JMP whole_stored_done
whole_stored_short:
	MOVOU (R8), X0
	MOVOU -16(R8)(CX*1), X1
	MOVOU X0, (SI)
	MOVOU X1, -16(SI)(CX*1)
whole_stored_done:
	MOVQ src_len+32(FP), AX
	ADDQ $2, AX
	MOVQ AX, ret+48(FP)
	RET
`
